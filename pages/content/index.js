  onLoad(options) {
    const cats = this.buildCats(this.data.articles);
    const favIds = favs.getIds().map(String);
    this.setData({ cats, favIds, favCount: favIds.length });
    // 初始化过滤列表（默认展示全部），再处理单项详情深链展开
    this.applyFilter();
    // 单项详情深链进来的场景：自动展开对应那篇避坑，并滚动到它
    if (options && options.id) {
      this.setData({ [`expanded.${options.id}`]: true });
      setTimeout(() => {
        wx.pageScrollTo({ selector: `#article-${options.id}`, duration: 300 });
      }, 350);
    }
  },

  // 从其它入口（如分享返回）回到本页时，同步最新收藏状态
  onShow() {
    const favIds = favs.getIds().map(String);
    this.setData({ favIds, favCount: favIds.length });
    if (this.data.activeCat === 'fav') this.applyFilter();
  },

  // 由文章 tag 聚合出分类与计数（每个文章 tag 即其主分类）
  buildCats(list) {
    const map = {};
    list.forEach((a) => {
      map[a.tag] = (map[a.tag] || 0) + 1;
    });
    return Object.keys(map).map((t) => ({ tag: t, count: map[t] }));
  },

  // 组合过滤：关键词 + 当前分类（含「我的收藏」）+ 收藏态
  applyFilter() {
    const kw = (this.data.keyword || '').trim().toLowerCase();
    const activeCat = this.data.activeCat;
    const favSet = new Set(this.data.favIds.map(String));
    const list = this.data.articles
      .filter((a) => {
        if (activeCat === 'fav' && !favSet.has(String(a.id))) return false;
        if (activeCat && activeCat !== 'fav' && a.tag !== activeCat) return false;
        if (kw) {
          const hay = (a.title + ' ' + a.tag + ' ' + a.desc).toLowerCase();
          if (!hay.includes(kw)) return false;
        }
        return true;
      })
      .map((a) => ({ ...a, faved: favSet.has(String(a.id)) }));
    this.setData({ filteredArticles: list });
  },

  onSearch(e) {
    this.setData({ keyword: e.detail.value });
    this.applyFilter();
  },

  clearSearch() {
    this.setData({ keyword: '' });
    this.applyFilter();
  },

  // 切换分类筛选（全部 / 我的收藏 / 具体分类）
  setCat(e) {
    this.setData({ activeCat: e.currentTarget.dataset.cat });
    this.applyFilter();
  },

  // 收藏 / 取消收藏：本机持久化，立即反馈并更新列表星标与收藏角标
  toggleFav(e) {
    const id = e.currentTarget.dataset.id;
    const now = favs.toggle(id);
    const favIds = favs.getIds().map(String);
    this.setData({ favIds, favCount: favIds.length });
    this.applyFilter();
    wx.showToast({ title: now ? '已收藏' : '已取消收藏', icon: 'none' });
  },

  toggle(e) {
    const id = e.currentTarget.dataset.id;
    this.setData({ [`expanded.${id}`]: !this.data.expanded[id] });
  },

